// Builds lib/history-data.js: one row per month of Bitcoin network history.
//
// Input is the free daily CSV from Coin Metrics (CC BY-NC 4.0):
//   curl -o btc.csv https://raw.githubusercontent.com/coinmetrics/data/master/csv/btc.csv
//   node scripts/build-history-data.mjs btc.csv
//
// Coin Metrics has no market price before 18 July 2010 (Mt. Gox's first day);
// those months keep a null price and the UI explains why.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const [csvPath] = process.argv.slice(2);
if (!csvPath) {
  console.error("usage: node scripts/build-history-data.mjs <coinmetrics btc.csv>");
  process.exit(1);
}

const [head, ...lines] = readFileSync(csvPath, "utf8").trim().split("\n");
const cols = head.split(",");
const col = (name) => {
  const i = cols.indexOf(name);
  if (i < 0) throw new Error(`column ${name} missing`);
  return i;
};
const C = { time: col("time"), price: col("PriceUSD"), hash: col("HashRate"), blocks: col("BlkCnt"), supply: col("SplyCur"), tx: col("TxCnt"), fee: col("FeeTotNtv") };
const num = (s) => (s === "" || s === undefined ? null : Number(s));

// Round to n significant digits so the bundle stays small.
const sig = (v, n = 3) => (v === null || v === 0 ? v : Number(v.toPrecision(n)));

const months = new Map();
let height = 0;
for (const line of lines) {
  const f = line.split(",");
  const day = f[C.time];
  const blocks = num(f[C.blocks]);
  // Rows past the last full day carry only reference rates; stop at the first one without blocks.
  if (blocks === null) break;
  height += blocks;
  const ym = day.slice(0, 7);
  if (!months.has(ym)) months.set(ym, { days: 0, hash: 0, hashDays: 0, tx: 0, feeUsd: 0, price: null, height: 0, supply: 0 });
  const m = months.get(ym);
  const price = num(f[C.price]);
  const hash = num(f[C.hash]);
  const tx = num(f[C.tx]) ?? 0;
  m.days++;
  if (hash !== null) {
    m.hash += hash;
    m.hashDays++;
  }
  m.tx += tx;
  if (price !== null) {
    m.price = price;
    m.feeUsd += (num(f[C.fee]) ?? 0) * price;
  }
  // Genesis (block 0) is not in BlkCnt, so the running count equals the tip height.
  m.height = height;
  m.supply = num(f[C.supply]) ?? m.supply;
}

const rows = [...months].map(([ym, m]) => [
  ym,
  m.price === null ? null : sig(m.price, 4),
  m.hashDays ? sig(m.hash / m.hashDays) : null,
  m.height,
  Math.round(m.supply),
  Math.round(m.tx / m.days),
  m.price === null || !m.tx ? null : sig(m.feeUsd / m.tx, 3),
]);

const out = `// Generated by scripts/build-history-data.mjs from Coin Metrics community data
// (github.com/coinmetrics/data, CC BY-NC 4.0). Do not edit by hand.
//
// One row per month: [month, close price USD, mean hashrate TH/s, block height at
// month end, BTC supply at month end, mean transactions per day, mean fee per tx USD].
// Price and fee are null before Mt. Gox opened in July 2010.
export const HISTORY = ${JSON.stringify(rows).replace(/\],\[/g, "],\n  [").replace(/^\[\[/, "[\n  [").replace(/\]\]$/, "],\n]")};
`;

const target = fileURLToPath(new URL("../lib/history-data.js", import.meta.url));
writeFileSync(target, out);
const last = rows[rows.length - 1];
console.log(`${rows.length} months, ${rows[0][0]} → ${last[0]}, height ${last[3]}, ${(out.length / 1024).toFixed(1)} KB`);
